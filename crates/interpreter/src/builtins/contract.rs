fn table() -> &'static HashMap<&'static str, BuiltinContract> {
    static T: OnceLock<HashMap<&'static str, BuiltinContract>> = OnceLock::new();
    T.get_or_init(|| {
        RAW.iter()
            .map(|(id, keys)| (*id, BuiltinContract { required: keys }))
            .collect()
    })
}

/// Look up the declared keys for a builtin id.
pub fn contract_for(id: &str) -> Option<BuiltinContract> {
    table().get(id).copied()
}

/// Every id in the contract table (for the bijection test).
pub fn contract_ids() -> impl Iterator<Item = &'static str> {
    table().keys().copied()
}
