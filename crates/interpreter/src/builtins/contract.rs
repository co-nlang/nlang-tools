//! Builtin key contracts (O76 / O78 ②).
//!
//! Lives in the registry, not in a builtin's value — putting the
//! declaration on the value would move the standard-root digest
//! and with it every root (O58). The spec defines the shape;
//! `contract_for` answers "which keys does this builtin bind?"
//! without running it.

use crate::value::Value;
use std::collections::HashMap;
use std::sync::OnceLock;

/// Keys a builtin binds. Extra keys on the argument (pipe wrap,
/// lifted names the builtin does not bind) are ignored; missing
/// required keys are a mismatch (apply layer → `Value::Top` → cocoon).
#[derive(Clone, Copy, Debug)]
pub struct BuiltinContract {
    pub required: &'static [&'static str],
}

impl BuiltinContract {
    pub fn satisfied(self, unified: &Value) -> bool {
        if self.required.is_empty() {
            return true;
        }
        match unified {
            Value::Combo(c) => self.required.iter().all(|k| c.get_field(k).is_some()),
            _ => false,
        }
    }
}

